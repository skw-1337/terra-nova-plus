// Terra Nova Plus - game keys (KEYBOARD tab): every command of the game's key card can be given another key or
// combination. The game reads the keyboard in one interrupt handler (its keyboard library: an event queue of
// "scancode | press << 8" words and a key state array); a routine of ours, called from that handler, turns the key
// pressed into the game's own one before the game sees it, and adds or hides Alt / Ctrl / Shift events around it
// (the game follows the modifiers from the queue). Only during missions: menus and names typed stay as they are.
// The handler has run since the game started, so DOSBox's dynamic core keeps it compiled and a patch written from
// outside would not be seen: the call to our routine is written by the game itself, from a hook in the camera
// set-up of the first mission (code not run before). Generated by _MODS/re/kb_cave.py (tested in an emulator).
