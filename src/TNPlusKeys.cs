    static int keysState = 0;                       // 0 to do, 1 in place, -1 nothing to change or unavailable
    static bool keysActive = false;

    static byte[] Rel32Call(uint from, uint to, int len)
    {
        byte[] b = new byte[len];
        b[0] = 0xE8; BitConverter.GetBytes((int)(to - (from + 5))).CopyTo(b, 1);
        for (int i = 5; i < len; i++) b[i] = 0x90;
        return b;
    }

    // 128 keys x (none, Shift, Ctrl, Alt): 0 nothing; 0x8000 | game key | its modifier << 8; 0x80FF = key taken away
    static byte[] BuildKeyMap()
    {
        ushort[] map = new ushort[512];
        foreach (GameKey g in GameKeys)
            if (g.Changed && !g.Fixed && g.Sc < 0x80) map[g.Sc * 4 + g.Mod] = (ushort)(0x8000 | g.DefSc | (g.DefMod << 8));
        foreach (GameKey g in GameKeys)
            if (g.Changed && g.DefSc < 0x80 && GameKeyOwner(g.DefSc, g.DefMod, null) == null) map[g.DefSc * 4 + g.DefMod] = 0x80FF;
        byte[] b = new byte[1024];
        Buffer.BlockCopy(map, 0, b, 0, 1024);
        return b;
    }

    static bool AllZero(byte[] b) { foreach (byte x in b) if (x != 0) return false; return true; }

    static void TryKeys()
    {
        keysState = -1;
        int n = GameKeys.FindAll(g => g.Changed).Count;
        if (n == 0)
        {   // nothing changed now, but an earlier run may have left its table in this game: emptied
            uint st = ReadUInt(KB_STATE);
            if (st == 1 || st == 2) { WriteInt(KB_ACTIVE, 0); Write(KB_MAP, new byte[1024]); }
            return;
        }
        uint site = 0, s0 = ReadUInt(KB_SITE);
        if (s0 > 0x200000 && s0 < 0x340000 && Same(Read(s0, 11), Rel32Call(s0, KB_MAP_FN, 11))) site = s0;   // already in place
        else
        {
            byte[] mem = Read(0x300000, 0x40000);
            int i = mem == null ? -1 : IndexOf(mem, Hex(KB_SITE_SIG), 0);
            if (i >= 0) site = 0x300000 + (uint)i;
        }
        if (site == 0 || !Same(Read(site + 0x6A, 8), Hex(KB_RESUME_SIG))) { Say("Game keys unavailable: keyboard handler not found", 300, 300); return; }
        int lang = -1;
        for (int l = 0; l < 2; l++)
        {
            byte[] h = Read(KB_HOOK[l], 8);
            if (Same(h, Hex(KB_HOOK_OLD)) || Same(h, Rel32Call(KB_HOOK[l], KB_INSTALL, 8))) lang = l;
        }
        byte[] code = Hex(KB_CODE_HEX), cur = Read(KB_CODE, code.Length);
        bool placed = s0 == site && ReadUInt(KB_STATE) >= 1;
        if (lang < 0 || (!AllZero(cur) && !Same(cur, code)) || (!placed && !AllZero(Read(KB_DATA, (int)(KB_DATA_END - KB_DATA)))))
        {
            Say("Game keys unavailable: unexpected game code or memory", 300, 300); return;
        }
        WriteInt(KB_ACTIVE, 0); keysActive = false;
        Write(KB_MAP, BuildKeyMap());
        if (!placed)
        {
            Write(KB_ACT, new byte[256]); WriteInt(KB_PM, 0);
            WriteInt(KB_SITE, (int)site); WriteInt(KB_RESUME, (int)(site + 0x6A));
            Write(KB_PATCH, Rel32Call(site, KB_MAP_FN, 11));
            Write(KB_CODE, code);                    // the code first, then what calls it
            WriteInt(KB_STATE, 1);
            Write(KB_HOOK[lang], Rel32Call(KB_HOOK[lang], KB_INSTALL, 8));
        }
        keysState = 1;
        Say("Game keys: " + n + " changed, active in missions", 0);
    }

    // during missions only: the menus and the names typed keep the keyboard as it is
    static void KeysFollowMission(bool inMission)
    {
        if (keysState != 1 || inMission == keysActive) return;
        keysActive = inMission;
        WriteInt(KB_ACTIVE, inMission ? 1 : 0);
    }
