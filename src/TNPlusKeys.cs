    static GameKey FindGameKey(string id) { return GameKeys.Find(g => g.Id == id); }

    // plain key of a command for the tool's own use (noclip moves follow the game's), or its default
    static int PlainKey(string id, int def)
    {
        GameKey g = FindGameKey(id);
        return g != null && g.Mod == 0 && g.Sc < 0x80 ? g.Sc : def;
    }

    static string ScanName(int sc)
    {
        switch (sc)
        {
            case 0xC9: return "PGUP"; case 0xD1: return "PGDN"; case 0xC7: return "HOME"; case 0xCF: return "END";
            case 0xC8: return "UP"; case 0xD0: return "DOWN"; case 0xCB: return "LEFT"; case 0xCD: return "RIGHT";
            case 0xD2: return "INS"; case 0xD3: return "DEL"; case 0x01: return "ESC"; case 0x39: return "SPACE";
            case 0x1C: return "ENTER"; case 0x0F: return "TAB";
        }
        return KeyName(sc);
    }
    static string ChordName(int sc, int mod) { return (mod > 0 ? MOD_NAMES[mod] + "+" : "") + ScanName(sc); }

    // ini: key_game_<id> = [SHIFT+|CTRL+|ALT+]scancode (hex), only the changed ones
    static void ParseGameKey(string id, string v)
    {
        GameKey g = FindGameKey(id);
        if (g == null || g.Fixed) return;
        int mod = 0; string s = v.ToUpperInvariant();
        for (int m = 1; m < 4; m++) if (s.StartsWith(MOD_NAMES[m] + "+")) { mod = m; s = s.Substring(MOD_NAMES[m].Length + 1); }
        int sc = Convert.ToInt32(s, 16);
        if (sc > 0 && sc < 0x80) { g.Sc = sc; g.Mod = mod; }
    }
    static string GameKeysIni()
    {
        StringBuilder sb = new StringBuilder();
        foreach (GameKey g in GameKeys)
            if (g.Changed) sb.Append("key_game_" + g.Id + " = " + (g.Mod > 0 ? MOD_NAMES[g.Mod] + "+" : "") + g.Sc.ToString("X2") + "\r\n");
        return sb.ToString();
    }
    static void ResetKeys()
    {
        ChosenLayout = -1;
        foreach (GameKey g in GameKeys) g.Mouse = 0;
        for (int i = 0; i < ToolMouse.Length; i++) ToolMouse[i] = 0;
        foreach (GameKey g in GameKeys) { g.Sc = g.DefSc; g.Mod = g.DefMod; }
        ScanFreelook = 0x15; ScanNoclip = 0x16; ScanDistance = 0x24; ScanSmoothing = 0x40; ScanStereo = 0x41;
        ResolveToolClashes();
    }

    // a game command on a plain key the tool uses (the game's previous target on Y, freelook's key) goes to the
    // first free key of these: K L ; 7 8 9 0
    static readonly int[] SPARE_KEYS = { 0x25, 0x26, 0x27, 0x08, 0x09, 0x0A, 0x0B };
    static void ResolveToolClashes()
    {
        foreach (GameKey g in GameKeys)
            if (!g.Fixed && g.Mod == 0 && g.Sc < 0x80 && ToolKeyOwner(g.Sc, -1) >= 0)
                foreach (int f in SPARE_KEYS)
                    if (ToolKeyOwner(f, -1) < 0 && GameKeyOwner(f, 0, null) == null) { g.Sc = f; break; }
    }

    // ---- mouse binds: the middle button, the side buttons and the wheel can press a command's key (or do a tool
    // action) as a second bind; left and right buttons stay the game's (fire, lock). None by default.
    static readonly string[] MOUSE_NAMES = { "", "MID", "M4", "M5", "WH+", "WH-" };
    static readonly string[] MOUSE_INI = { "", "MID", "M4", "M5", "WHEELUP", "WHEELDOWN" };
    static readonly string[] MOUSE_LONG = { "", "middle click", "side button 4", "side button 5", "wheel up", "wheel down" };
    static readonly string[] TOOL_IDS = { "freelook", "noclip", "distance", "stereo", "smoothing" };   // KEY_WHAT order
    static readonly int[] ToolMouse = new int[5];

    static string MouseOwner(int m)
    {
        if (m == 0) return null;
        GameKey g = GameKeys.Find(k => k.Mouse == m);
        if (g != null) return g.Name.ToLowerInvariant();
        int t = Array.IndexOf(ToolMouse, m);
        return t >= 0 ? KEY_WHAT[t] : null;
    }

    // a mouse input to a game command (g) or a tool action (tool); m = 0 removes it
    static string AssignMouse(GameKey g, int tool, int m)
    {
        string name = g != null ? g.Name.ToLowerInvariant() : KEY_WHAT[tool];
        string before = MouseOwner(m);
        foreach (GameKey o in GameKeys) if (m != 0 && o.Mouse == m) o.Mouse = 0;
        for (int i = 0; i < ToolMouse.Length; i++) if (m != 0 && ToolMouse[i] == m) ToolMouse[i] = 0;
        if (g != null) g.Mouse = m; else ToolMouse[tool] = m;
        if (m == 0) return name + ": mouse bind removed";
        return name + ": " + MOUSE_LONG[m] + " (and still " + (g != null ? ChordName(g.Sc, g.Mod) : ScanName(GetKey(tool))) + ")" +
            (before != null && before != name ? ", taken from " + before : "");
    }

    static void ParseMouse(string id, string v)
    {
        int m = Array.IndexOf(MOUSE_INI, v.ToUpperInvariant());
        if (m <= 0) return;
        int t = Array.IndexOf(TOOL_IDS, id);
        GameKey g = FindGameKey(id);
        if (t >= 0) ToolMouse[t] = m; else if (g != null && !g.Fixed) g.Mouse = m;
    }
    static string MouseIni()
    {
        StringBuilder sb = new StringBuilder();
        foreach (GameKey g in GameKeys) if (g.Mouse > 0) sb.Append("mouse_" + g.Id + " = " + MOUSE_INI[g.Mouse] + "\r\n");
        for (int i = 0; i < ToolMouse.Length; i++) if (ToolMouse[i] > 0) sb.Append("mouse_" + TOOL_IDS[i] + " = " + MOUSE_INI[ToolMouse[i]] + "\r\n");
        return sb.ToString();
    }
    static bool AnyMouseBind() { return GameKeys.Exists(g => g.Mouse > 0) || Array.Exists(ToolMouse, m => m > 0); }

    // the command's key pressed as if typed (it goes through the key translation like the keyboard)
    [StructLayout(LayoutKind.Sequential)] struct KEYBDINPUT { public ushort wVk, wScan; public uint dwFlags, time; public IntPtr dwExtraInfo; }
    [StructLayout(LayoutKind.Sequential)] struct MOUSEINPUT { public int dx, dy; public uint mouseData, dwFlags, time; public IntPtr dwExtraInfo; }
    [StructLayout(LayoutKind.Explicit)] struct INPUTUNION { [FieldOffset(0)] public KEYBDINPUT ki; [FieldOffset(0)] public MOUSEINPUT mi; }
    [StructLayout(LayoutKind.Sequential)] struct INPUT { public uint type; public INPUTUNION u; }
    [DllImport("user32.dll", SetLastError = true)] static extern uint SendInput(uint n, INPUT[] inputs, int size);

    static void SendScan(int sc, bool up)
    {
        INPUT[] i = new INPUT[1];
        i[0].type = 1;
        i[0].u.ki.wScan = (ushort)(sc & 0x7F);
        i[0].u.ki.dwFlags = 0x0008 | (up ? 0x0002u : 0) | (sc >= 0x80 ? 0x0001u : 0);   // SCANCODE, KEYUP, EXTENDED
        SendInput(1, i, Marshal.SizeOf(typeof(INPUT)));
    }
    static void SendChord(GameKey g, bool down)
    {
        int msc = g.Mod == 1 ? 0x2A : g.Mod == 2 ? 0x1D : g.Mod == 3 ? 0x38 : 0;
        if (down) { if (msc != 0) SendScan(msc, false); SendScan(g.Sc, false); }
        else { SendScan(g.Sc, true); if (msc != 0) SendScan(msc, true); }
    }

    // ---- assigning keys: the same key is never used twice, the two swap when they can
    static readonly int[] MODIFIER_SC = { 0x1D, 0x2A, 0x36, 0x38 };
    static int ToolKeyOwner(int sc, int except)
    {
        for (int i = 0; i < KEY_WHAT.Length; i++) if (i != except && GetKey(i) == sc) return i;
        return -1;
    }
    static GameKey GameKeyOwner(int sc, int mod, GameKey except)
    {
        return GameKeys.Find(g => g != except && g.Sc == sc && g.Mod == mod);
    }

    // a game command gets a new key; returns the message to show
    static string AssignGameKey(GameKey g, int sc, int mod, bool ext)
    {
        if (ext || sc <= 1 || sc >= 0x80 || Array.IndexOf(MODIFIER_SC, sc) >= 0)
            return "that key can't be used (Esc, extended keys like the arrows): pick another one";
        if (sc == g.Sc && mod == g.Mod) return g.Name.ToLowerInvariant() + ": unchanged";
        GameKey o = GameKeyOwner(sc, mod, g);
        int t = mod == 0 ? ToolKeyOwner(sc, -1) : -1;
        if (o != null && o.Fixed) return ChordName(sc, mod) + " is the game's " + o.Name.ToLowerInvariant() + " key: pick another one";
        if (t >= 0 && (g.Mod != 0 || g.Sc >= 0x80 || Array.IndexOf(KEY_RESERVED, g.Sc) >= 0))
            return ChordName(sc, mod) + " is Terra Nova Plus " + KEY_WHAT[t] + ": change that one first";
        string msg = g.Name.ToLowerInvariant() + ": " + ChordName(sc, mod);
        if (o != null) { o.Sc = g.Sc; o.Mod = g.Mod; msg += ", " + o.Name.ToLowerInvariant() + " moved to " + ChordName(o.Sc, o.Mod); }
        if (t >= 0) { SetKey(t, g.Sc); msg += ", " + KEY_WHAT[t] + " moved to " + ScanName(g.Sc); }
        g.Sc = sc; g.Mod = mod;
        return msg;
    }

    // a key of the tool itself (plain key); returns the message, null when refused with the reserved-key text
    static string AssignToolKey(int k, int sc, bool ext)
    {
        if (ext || sc == 0 || Array.IndexOf(KEY_RESERVED, sc) >= 0)
            return "that key is taken by the game or the tool (Esc, O, noclip up / down, Ctrl, Shift, Alt, arrows...): pick another one";
        if (sc == GetKey(k)) return KEY_WHAT[k] + ": unchanged";
        string msg = KEY_WHAT[k] + ": " + ScanName(sc);
        int other = ToolKeyOwner(sc, k);
        GameKey o = GameKeyOwner(sc, 0, null);
        if (o != null && o.Fixed) return ScanName(sc) + " is the game's " + o.Name.ToLowerInvariant() + " key: pick another one";
        if (other >= 0) { SetKey(other, GetKey(k)); msg += ", " + KEY_WHAT[other] + " moved to " + ScanName(GetKey(other)); }
        if (o != null) { o.Sc = GetKey(k); o.Mod = 0; msg += ", " + o.Name.ToLowerInvariant() + " moved to " + ScanName(o.Sc); }
        SetKey(k, sc);
        return msg;
    }

    // ---- keyboard layout presets. GAME = the game's own keys. The others: moves on W A S D as in today's games
    // (Z Q S D on AZERTY: the game reads key positions): S back and X stop (the game: S stop, X back), A / D sidestep
    // and Z / C turn (the game: A / D turn, Z / C sidestep);
    // look and number keys keep their place; the letter shortcuts follow the letter printed on the keyboard, a letter
    // that lands on a key already used keeps the game's place. Other QWERTY countries (UK, ES, IT, Nordic...) have
    // their letters where QWERTY has them.
    static readonly string[] LAYOUT_NAMES = { "GAME", "QWERTY", "AZERTY", "QWERTZ", "DVORAK", "COLEMAK", "CUSTOM" };
    const int LAYOUT_COUNT = 6;
    static readonly string[][] LAYOUT_ROWS = {      // letter rows from scancodes 0x10, 0x1E, 0x2C
        new[] { "QWERTYUIOP", "ASDFGHJKL;", "ZXCVBNM" },
        new[] { "AZERTYUIOP", "QSDFGHJKLM", "WXCVBN" },
        new[] { "QWERTZUIOP", "ASDFGHJKL", "YXCVBNM" },
        new[] { "',.PYFGCRL", "AOEUIDHTNS", ";QJKXBMWVZ" },
        new[] { "QWFPGJLUY;", "ARSTDHNEIO", "ZXCVBKM" } };
    static readonly string[,] LETTER_KEYS = {
        { "full", "G" }, { "ir", "I" }, { "recentre", "N" }, { "v360", "B" }, { "maphud", "M" }, { "pause", "P" },
        { "tnext", "T" }, { "tprev", "Y" }, { "o_attack", "A" }, { "o_cover", "C" }, { "o_caution", "D" }, { "o_form", "F" },
        { "o_hold", "H" }, { "o_follow", "M" }, { "o_nav", "N" }, { "o_pickup", "P" }, { "o_retreat", "R" },
        { "o_status", "S" }, { "o_target", "T" }, { "exit", "X" } };

    // the other keys a command can use, as printed on each keyboard (the digits are the same everywhere)
    static readonly string[][] LAYOUT_PUNCT = {      // scancodes 0C 0D 1A 1B 28 29 2B 32 33 34 35 (empty: a letter row)
        new[] { "-", "=", "[", "]", "'", "`", "\\", "", ",", ".", "/" },
        new[] { ")", "=", "^", "$", "\u00d9", "\u00b2", "*", ",", ";", ":", "!" },
        new[] { "\u00df", "\u00b4", "\u00dc", "+", "\u00c4", "^", "#", "", ",", ".", "-" },
        new[] { "[", "]", "/", "=", "-", "`", "\\", "", "", "", "" },
        new[] { "-", "=", "[", "]", "'", "`", "\\", "", ",", ".", "/" } };
    static readonly int[] PUNCT_SC = { 0x0C, 0x0D, 0x1A, 0x1B, 0x28, 0x29, 0x2B, 0x32, 0x33, 0x34, 0x35 };

    // keys are shown as printed on the keyboard of the preset picked (GAME, CUSTOM: the Windows keyboard)
    static int DisplayLayout() { return ChosenLayout >= 1 && ChosenLayout < LAYOUT_COUNT ? ChosenLayout : -1; }
    static string LayoutKeyName(int layout, int sc)
    {
        if (sc >= 0x02 && sc <= 0x0B) return sc == 0x0B ? "0" : ((char)('1' + sc - 2)).ToString();
        int[] start = { 0x10, 0x1E, 0x2C };
        for (int r = 0; r < 3; r++)
        {
            string row = LAYOUT_ROWS[layout - 1][r];
            if (sc >= start[r] && sc < start[r] + row.Length) return row[sc - start[r]].ToString();
        }
        int i = Array.IndexOf(PUNCT_SC, sc);
        return i >= 0 && LAYOUT_PUNCT[layout - 1][i] != "" ? LAYOUT_PUNCT[layout - 1][i] : null;
    }

    static int LetterSc(int layout, char c)
    {
        int[] start = { 0x10, 0x1E, 0x2C };
        for (int r = 0; r < 3; r++) { int i = LAYOUT_ROWS[layout - 1][r].IndexOf(c); if (i >= 0) return start[r] + i; }
        return 0;
    }

    // the chords a preset gives: game defaults, then the letters, as long as they land on a free key
    static int[,] LayoutChords(int layout)
    {
        int n = GameKeys.Count;
        int[,] ch = new int[n, 2];
        for (int i = 0; i < n; i++) { ch[i, 0] = GameKeys[i].DefSc; ch[i, 1] = GameKeys[i].DefMod; }
        if (layout > 0) LayoutMoves(layout, ch);
        for (int i = 0; i < n; i++)                 // off the tool's keys, like ResolveToolClashes
            if (ch[i, 1] == 0 && ToolKeyOwner(ch[i, 0], -1) >= 0)
                foreach (int f in SPARE_KEYS)
                {
                    bool used = ToolKeyOwner(f, -1) >= 0;
                    for (int j = 0; j < n && !used; j++) used = ch[j, 0] == f && ch[j, 1] == 0;
                    if (!used) { ch[i, 0] = f; break; }
                }
        return ch;
    }

    static void LayoutMoves(int layout, int[,] ch)
    {
        int n = GameKeys.Count;
        Func<string, int> at = id => GameKeys.FindIndex(g => g.Id == id);
        ch[at("back"), 0] = 0x1F; ch[at("stop"), 0] = 0x2D;        // S back, X stop
        ch[at("sidel"), 0] = 0x1E; ch[at("sider"), 0] = 0x20;      // A / D sidestep (strafe), the mouse turns
        ch[at("turnl"), 0] = 0x2C; ch[at("turnr"), 0] = 0x2E;      // Z / C turn
        for (bool moved = true; moved; )
        {
            moved = false;
            for (int k = 0; k < LETTER_KEYS.GetLength(0); k++)
            {
                int i = GameKeys.FindIndex(g => g.Id == LETTER_KEYS[k, 0]);
                int sc = LetterSc(layout, LETTER_KEYS[k, 1][0]);
                if (i < 0 || sc == 0 || sc == ch[i, 0]) continue;
                bool free = !(ch[i, 1] == 0 && ToolKeyOwner(sc, -1) >= 0);
                for (int j = 0; j < n && free; j++) if (j != i && ch[j, 0] == sc && ch[j, 1] == ch[i, 1]) free = false;
                if (free) { ch[i, 0] = sc; moved = true; }
            }
        }
    }

    static int ChosenLayout = -1;                   // ini keys_layout: the preset picked last (QWERTZ gives QWERTY's keys)

    static void ApplyLayout(int layout)
    {
        ChosenLayout = layout;
        int[,] ch = LayoutChords(layout);
        for (int i = 0; i < GameKeys.Count; i++) { GameKeys[i].Sc = ch[i, 0]; GameKeys[i].Mod = ch[i, 1]; }
    }

    // the preset the game keys match (the detected layout first), or CUSTOM
    static int CurrentLayout()
    {
        int det = DetectLayout();
        List<int> order = new List<int>();
        if (ChosenLayout >= 0 && ChosenLayout < LAYOUT_COUNT) order.Add(ChosenLayout);
        if (!order.Contains(det)) order.Add(det);
        for (int l = 0; l < LAYOUT_COUNT; l++) if (!order.Contains(l)) order.Add(l);
        foreach (int l in order)
        {
            int[,] ch = LayoutChords(l);
            bool same = true;
            for (int i = 0; i < GameKeys.Count && same; i++) same = GameKeys[i].Sc == ch[i, 0] && GameKeys[i].Mod == ch[i, 1];
            if (same) return l;
        }
        return LAYOUT_COUNT;
    }

    // the Windows keyboard layout, from where its letters are
    static int DetectLayout()
    {
        Func<char, uint> sc = c => MapVirtualKey((uint)c, 0);
        if (sc('A') == 0x10) return 2;
        if (sc('Z') == 0x15) return 3;
        if (sc('P') == 0x13) return 4;
        if (sc('F') == 0x12) return 5;
        return 1;
    }

