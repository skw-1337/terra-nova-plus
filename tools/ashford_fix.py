# Ashford "Deceased" (original bug), after TNova Native (Callemann, engine/features/hud_overlays.py, MIT).
# Ashford leaves the SFC for good, but the Outfit screen keeps listing him as "Away on Mission" (status 3) in the
# missions after. The row text comes from the string lookup EN 0x2E3194 (eax = resource << 16 | index, returns a
# char *); its call for status 3 (EN 0x2BA8CF, eax = 0x05AB0148) now goes through a check: Ashford's row (ebp =
# row 7 * 494) and campaign missions 21 to 28 ([EN 0x359708]) give "Deceased", anything else the original text.
# French exe: the same code 0x1C further (call FR 0x2BA8EB to 0x2E32D4, mission [FR 0x359724], found by code
# signature against the English one), "Décédé" in the game's code page 850 (as its own "Blessé(e)").
#   python ashford_fix.py         prints the pieces (address, old, new)
#   python ashford_fix.py test    runs the code in an emulator (Unicorn)
#   python ashford_fix.py cs      C# table for TN+ (src/TNPlusAshford.cs)
import struct, sys
from keystone import Ks, KS_ARCH_X86, KS_MODE_32

CAVE, TEXT = 0x469FB0, 0x469FE0   # free gap of the tool's code area (after the view fix stubs, 0x469F9B-0x46A000)
# per exe: hooked call, string lookup, mission variable, text
EXES = [('en', 0x2BA8CF, 0x2E3194, 0x359708, b'Deceased\0'),
        ('fr', 0x2BA8EB, 0x2E32D4, 0x359724, 'Décédé\0'.encode('cp850'))]
RES_AWAY, ASHFORD_ROW = 0x05AB0148, 7 * 494
FIRST, LAST = 21, 28              # the campaign missions after his departure (TNova Native's window)

SRC = '''
    cmp eax, {RES_AWAY}
    jne original
    cmp ebp, {ROW}
    jne original
    cmp dword ptr [{MISSION}], {FIRST}
    jb original
    cmp dword ptr [{MISSION}], {LAST}
    ja original
    mov eax, {TEXT}
    ret
original:
    jmp {LOOKUP}
'''


def asm(src, at):
    return bytes(Ks(KS_ARCH_X86, KS_MODE_32).asm(src, at)[0])


def build(exe=0):
    _, SITE, LOOKUP, MISSION, text = EXES[exe]
    code = asm(SRC.format(RES_AWAY=RES_AWAY, ROW=ASHFORD_ROW, MISSION=MISSION, FIRST=FIRST, LAST=LAST, TEXT=TEXT,
                          LOOKUP=LOOKUP), CAVE)
    assert CAVE + len(code) <= TEXT and TEXT + len(text) <= 0x46A000, len(code)
    hook = b'\xe8' + struct.pack('<i', CAVE - (SITE + 5))
    old = b'\xe8' + struct.pack('<i', LOOKUP - (SITE + 5))
    return [(CAVE, bytes(len(code)), code), (TEXT, bytes(len(text)), text), (SITE, old, hook)]


def test():
    from unicorn import Uc, UC_ARCH_X86, UC_MODE_32
    from unicorn.x86_const import UC_X86_REG_EAX, UC_X86_REG_EBP, UC_X86_REG_ESP
    STOP = 0x1000                                       # return address: the run ends there
    ok = True
    for exe, res, row, mission, want in [(e, RES_AWAY, ASHFORD_ROW, m, m in range(FIRST, LAST + 1))
                                         for e in range(len(EXES)) for m in (1, 20, 21, 27, 28, 29, 40)] + \
            [(e, RES_AWAY, 6 * 494, 27, False) for e in range(len(EXES))] + [(e, 0x05AB0147, ASHFORD_ROW, 27, False) for e in range(len(EXES))]:
        name, _, LOOKUP, MISSION, _ = EXES[exe]
        u = Uc(UC_ARCH_X86, UC_MODE_32)
        u.mem_map(0, 0x500000)
        for at, _, new in build(exe):
            u.mem_write(at, new)
        u.mem_write(LOOKUP, b'\xb8\x11\x11\x11\x11\xc3')  # stand-in lookup: eax = 0x11111111
        u.mem_write(MISSION, struct.pack('<I', mission))
        u.mem_write(0x8000, struct.pack('<I', STOP))
        u.reg_write(UC_X86_REG_ESP, 0x8000)
        u.reg_write(UC_X86_REG_EAX, res)
        u.reg_write(UC_X86_REG_EBP, row)
        u.emu_start(CAVE, STOP)
        got = u.reg_read(UC_X86_REG_EAX) == TEXT
        print('%s res %#x row %d mission %2d -> %s' % (name, res, row // 494, mission, 'Deceased' if got else 'original'))
        ok &= got == want
    print('OK' if ok else 'FAILED')
    return ok


def cs():
    ps = [build(e) for e in range(len(EXES))]
    row = lambda f: ', '.join('new %s[] { %s }' % (f[0], ', '.join(f[1](x) for x in p)) for p in ps)
    return '\n'.join([
        '// Generated by tools/ashford_fix.py (python ashford_fix.py cs > ../src/TNPlusAshford.cs): do not edit.',
        '// Ashford "Deceased" on the Outfit screen after his departure, English then French exe (see ashford_fix.py).',
        'static class AshfordFix',
        '{',
        '    public static readonly uint[][] At = { %s };' % row(('uint', lambda x: '0x%X' % x[0])),
        '    public static readonly string[][] Old = { %s };' % row(('string', lambda x: '"%s"' % x[1].hex().upper())),
        '    public static readonly string[][] New = { %s };' % row(('string', lambda x: '"%s"' % x[2].hex().upper())),
        '}', ''])


if __name__ == '__main__':
    arg = sys.argv[1] if len(sys.argv) > 1 else ''
    if arg == 'test':
        sys.exit(0 if test() else 1)
    elif arg == 'cs':
        sys.stdout.write(cs())
    else:
        for e in range(len(EXES)):
            for at, old, new in build(e):
                print('%s 0x%X  %s -> %s' % (EXES[e][0], at, old.hex(), new.hex()))
