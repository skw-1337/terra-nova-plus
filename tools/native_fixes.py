# Two original bugs fixed in place (same length, no cave), after TNova Native (Callemann, MIT):
#  - sky: the clouds jump up and down while walking (engine/features/terrain_raster.py, sky_row_body). Each screen
#    row of the sky ray (EN 0x2A73DE-0x2A7423) was the previous row's plus a rounded step, so the rounding piled up
#    from row to row and a small tilt of the walk moved the cloud layer by a visible step. Each row is now worked out
#    directly from the view coefficients (EN 0x41EB9E-0x41EBB2).
#  - drone readiness: the damage test of a drone's weapons reads the energy record of the weapon as null and then
#    reads low memory (EN 0x28F05F, engine/features/weapon_timing.py, readiness_body). A null record now answers
#    "not enough charge", which the damage code counts as an intact weapon.
# French exe: the same code (sky 0x10 earlier, its variables 0xB0 further; drone readiness at the same address, its
# table 0xB0 further), found by code signature against the English one.
#   python native_fixes.py         prints the pieces
#   python native_fixes.py cs      C# table for TN+ (src/TNPlusNative.cs)
import sys
from keystone import Ks, KS_ARCH_X86, KS_MODE_32

# per exe: sky site, its variables (9E, A2, A6, AA, AE, B2 in the English exe), drone site, energy table
EXES = [('en', 0x2A73DE, 0x41EB9E, 0x28F05F, 0x395118),
        ('fr', 0x2A73CE, 0x41EC4E, 0x28F05F, 0x3951C8)]
SKY_LEN = 0x45
SKY_OLD = ('8b54245489c18944245429d1a1{aa}89ca8b5c240cf7ea0facd01089ca01c3a1{b2}8b742410f7ea0facd01089ca01c6'
           'a1{ae}f7ea0facd0108b54241429c2')
DRONE_OLD = '31ffbb01000000668bb8{tab}'


def asm(src, at):
    return bytes(Ks(KS_ARCH_X86, KS_MODE_32).asm(src, at)[0])


def le(v):
    return v.to_bytes(4, 'little').hex()


def build(exe=0):
    _, sky, v, drone, tab = EXES[exe]
    sky_old = bytes.fromhex(SKY_OLD.format(aa=le(v + 0xC), b2=le(v + 0x14), ae=le(v + 0x10)))
    sky_new = asm('''
        mov ecx, eax
        mov eax, [{aa}]
        imul ecx
        shrd eax, edx, 16
        sub eax, [{v9e}]
        mov ebx, eax
        mov eax, [{b2}]
        imul ecx
        shrd eax, edx, 16
        sub eax, [{a6}]
        mov esi, eax
        mov eax, [{ae}]
        imul ecx
        shrd eax, edx, 16
        mov edx, [{a2}]
        sub edx, eax
    '''.format(aa=v + 0xC, v9e=v, b2=v + 0x14, a6=v + 8, ae=v + 0x10, a2=v + 4), sky)
    assert len(sky_old) == SKY_LEN and len(sky_new) <= SKY_LEN
    sky_new = sky_new.ljust(SKY_LEN, b'\x90')
    drone_old = bytes.fromhex(DRONE_OLD.format(tab=le(tab)))
    drone_new = asm('''
        test edx, edx
        jz 0x28F07F
        push 1
        pop ebx
        movzx edi, word ptr [eax + {tab}]
    '''.format(tab=tab), drone)
    assert len(drone_new) == len(drone_old)
    return [(sky, sky_old, sky_new)], [(drone, drone_old, drone_new)]


def cs():
    out = ['// Generated by tools/native_fixes.py (python native_fixes.py cs > ../src/TNPlusNative.cs): do not edit.',
           '// Clouds that jump while walking, null energy record in the drone damage test: in place, English then French',
           '// exe (see native_fixes.py).', 'static class NativeFixes', '{']
    for k, name in enumerate(('Sky', 'Drone')):
        ps = [build(e)[k] for e in range(len(EXES))]
        row = lambda typ, f: ', '.join('new %s[] { %s }' % (typ, ', '.join(f(x) for x in p)) for p in ps)
        out += ['    public static readonly uint[][] %sAt = { %s };' % (name, row('uint', lambda x: '0x%X' % x[0])),
                '    public static readonly string[][] %sOld = { %s };' % (name, row('string', lambda x: '"%s"' % x[1].hex().upper())),
                '    public static readonly string[][] %sNew = { %s };' % (name, row('string', lambda x: '"%s"' % x[2].hex().upper()))]
    return '\n'.join(out + ['}', ''])


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'cs':
        sys.stdout.write(cs())
    else:
        for e in range(len(EXES)):
            for part in build(e):
                for at, old, new in part:
                    print('%s 0x%X  %s -> %s' % (EXES[e][0], at, old.hex(), new.hex()))
